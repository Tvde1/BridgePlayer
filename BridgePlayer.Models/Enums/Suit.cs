namespace BridgePlayer.Models.Enums;

/// <summary>
/// Represents one of the four suits in a standard deck of playing cards.
/// </summary>
public enum Suit : byte
{
    /// <summary>The Spades suit (♠).</summary>
    Spades = 1,
    /// <summary>The Hearts suit (♥).</summary>
    Hearts = 2,
    /// <summary>The Diamonds suit (♦).</summary>
    Diamonds = 3,
    /// <summary>The Clubs suit (♣).</summary>
    Clubs = 4,
}
